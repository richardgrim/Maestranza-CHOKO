CREATE TABLE ordenes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id bigint NOT NULL REFERENCES clientes(id),
    componente varchar(150) NOT NULL CHECK (btrim(componente) <> ''),
    servicios varchar(1500) NOT NULL CHECK (btrim(servicios) <> ''),
    recepcion date NOT NULL,
    entrega_estimada date NOT NULL CHECK (entrega_estimada >= recepcion)
);

CREATE INDEX ordenes_cliente_id_id_idx ON ordenes(cliente_id, id DESC);
