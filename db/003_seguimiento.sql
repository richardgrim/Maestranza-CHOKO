ALTER TABLE ordenes ADD COLUMN estado varchar(24) NOT NULL DEFAULT 'SIN_REGISTRO'
    CHECK (estado IN ('SIN_REGISTRO','RECIBIDA','EN_PROCESO','LISTA','ENTREGADA'));

CREATE TABLE seguimiento (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden_id bigint NOT NULL REFERENCES ordenes(id),
    solicitud uuid NOT NULL,
    tipo varchar(12) NOT NULL CHECK (tipo IN ('REPUESTO','ESTADO','AVISO')),
    detalle varchar(500) NOT NULL CHECK (btrim(detalle) <> ''),
    cantidad integer,
    medio varchar(10),
    fecha_aviso date,
    usuario text NOT NULL,
    registrado timestamptz NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (orden_id, solicitud),
    CHECK ((tipo = 'REPUESTO' AND cantidad IS NOT NULL AND cantidad > 0 AND medio IS NULL AND fecha_aviso IS NULL)
        OR (tipo = 'ESTADO' AND cantidad IS NULL AND medio IS NULL AND fecha_aviso IS NULL)
        OR (tipo = 'AVISO' AND cantidad IS NULL AND medio IS NOT NULL AND medio IN ('Llamada','WhatsApp') AND fecha_aviso IS NOT NULL))
);
CREATE INDEX seguimiento_orden_idx ON seguimiento (orden_id, id DESC);
